const assert = require("node:assert/strict");
const { harness, TFile, bytes, digest, delay } = require("./test-harness.cjs");
const done = [];
const deferred = () => { let resolve; const promise = new Promise(r => resolve = r); return { promise, resolve }; };
function isolated(files = []) {
  const result = harness({ files });
  result.instance.checkServiceStatus = async () => {};
  result.instance.refreshAccount = async () => result.instance.settings.account;
  result.instance.authorizedRequest = async route => { assert.equal(route, "/v1/sync/manifest"); return { files: [] }; };
  return result;
}
(async () => {
  const { AccountRefresh, runBounded, safeSyncPath, ServiceError } = harness().support();
  for (const path of ["../x.md", "a/../b.md", ".obsidian/x.md", ".trash/x.md", "a//b.md", "a\\b.md"]) assert.equal(safeSyncPath(path), false);
  assert.equal(safeSyncPath("中文/笔记.txt"), true);
  let identity = "a", calls = 0, applied = [], errors = [], time = 10000, gate = deferred();
  const refresh = new AccountRefresh({ identity: () => identity, read: async () => { calls++; return gate.promise; }, apply: async a => { applied.push(a); }, error: e => errors.push(e), now: () => time });
  const one = refresh.refresh(true), two = refresh.refresh(true);
  gate.resolve({ id: "a", quotaBytes: 5, usedBytes: 1 }); await Promise.all([one, two]);
  assert.equal(calls, 1); assert.equal(applied[0].quotaBytes, 5);
  await refresh.refresh(false, 10000); assert.equal(calls, 1);
  time += 10000; gate = deferred(); const stale = refresh.refresh(); identity = "";
  gate.resolve({ id: "a", quotaBytes: 99, usedBytes: 1 }); await stale;
  assert.equal(applied.length, 1, "logout ignores late quota response");
  identity = "b"; gate = deferred(); const current = refresh.refresh(true);
  gate.resolve({ id: "b", quotaBytes: 8, usedBytes: 1 }); await current;
  assert.equal(applied.at(-1).id, "b");
  done.push("quota refresh coalescing, interval, logout and account isolation");
  let active = 0, peak = 0, finished = [];
  await runBounded([1, 2, 3, 4], 2, () => 10, 20, async i => { active++; peak = Math.max(peak, active); await delay(5); finished.push(i); active--; }, () => false);
  assert.equal(peak, 2); assert.equal(finished.length, 4);
  active = 0; peak = 0;
  await runBounded([1, 2], 2, () => 30, 20, async () => { active++; peak = Math.max(peak, active); await delay(5); active--; }, () => false);
  assert.equal(peak, 1, "large files alone");
  finished = [];
  await assert.rejects(runBounded([1, 2, 3], 2, () => 1, 20, async i => { if (i === 1) throw Error("stop"); await delay(10); finished.push(i); }, () => false), /stop/);
  assert.deepEqual(finished, [2], "started work drained before returning on failure");
  done.push("bounded concurrency, memory budget and drain-before-return");
  const token = harness().instance; token.settings.refreshToken = "refresh"; token.settings.tokenExpiresAt = Date.now() - 1;
  let refreshCalls = 0; const tokenGate = deferred();
  token.request = async route => { if (route === "/v1/auth/plugin-refresh") { refreshCalls++; await tokenGate.promise; return { id: "account-a", token: "new-token", refreshToken: "new-refresh", expiresIn: 900 }; } return {}; };
  const requests = [token.authorizedRequest("/one"), token.authorizedRequest("/two")];
  tokenGate.resolve(); await Promise.all(requests); assert.equal(refreshCalls, 1);
  token.settings.tokenExpiresAt = Date.now() - 1; const logoutGate = deferred();
  token.request = async () => { await logoutGate.promise; return { id: "account-a", token: "late", refreshToken: "late", expiresIn: 900 }; };
  const late = token.refreshPluginToken(); token.authEpoch = (token.authEpoch || 0) + 1; token.settings.token = ""; logoutGate.resolve();
  await assert.rejects(late); assert.equal(token.settings.token, "");
  done.push("parallel token refresh single flight, no late re-login");
  const txt = isolated(); const remote = { path: "folder/web.txt", revision: digest("hello"), size: 5 };
  txt.instance.authorizedRequest = async route => { assert.equal(route, "/v1/sync/manifest"); return { files: [remote, { path: "opaque.bin", revision: "old", size: 1 }] }; };
  txt.instance.settings.state["opaque.bin"] = { hash: "old", remoteRevision: "old" };
  txt.instance.remoteBytes = async () => bytes("hello");
  await txt.instance.sync(false); assert.equal(txt.store.get(remote.path).content.toString(), "hello");
  await txt.instance.sync(false); assert.equal(txt.instance.lastSyncReport.errors.length, 0);
  const priorReads = txt.metrics.reads; await txt.instance.sync(false); assert.equal(txt.metrics.reads, priorReads, "unchanged files reuse in-memory digests");
  assert.equal(txt.instance.settings.state["opaque.bin"].remoteRevision, "old");
  done.push("TXT remains on second sync; unsupported files never deleted; unchanged digest cache");
  txt.instance.pendingChanges = false; txt.instance.markPending(new TFile("unsupported.bin", "x"));
  assert.equal(txt.instance.pendingChanges, false, "unsupported file events do not permanently mark the vault dirty");
  const batch = isolated(["one.md", "bad.md", "three.md"].map(name => new TFile(name, name)));
  const completed = [];
  batch.instance.upload = async (file, hash, content) => { await delay(5); if (file.path === "bad.md") throw new ServiceError("quota", 413); completed.push(file.path); batch.instance.remember(file.path, hash, hash, content); };
  await batch.instance.sync(false);
  assert.deepEqual(completed.sort(), ["one.md", "three.md"]); assert.equal(batch.instance.lastSyncReport.errors.length, 1);
  assert.equal(batch.instance.syncing, false); assert.equal(batch.instance.pendingChanges, true); assert.ok(batch.metrics.saves > 0);
  assert.ok(batch.instance.settings.state["one.md"]); assert.ok(batch.instance.settings.state["three.md"]);
  done.push("one failed file does not block others; partial progress saved; sync button unlocked");
  const cancelled = isolated([1, 2, 3].map(i => new TFile(i + ".md", "data")));
  const cancelGate = deferred(); let started = 0;
  cancelled.instance.upload = async () => { started++; await cancelGate.promise; cancelled.instance.checkRun(); };
  const running = cancelled.instance.sync(false);
  while (started < 2) await delay(1);
  cancelled.instance.cancelSync(); assert.equal(cancelled.instance.syncing, true);
  await cancelled.instance.sync(false); assert.equal(started, 2);
  cancelGate.resolve(); await running; assert.equal(started, 2); assert.equal(cancelled.instance.syncing, false);
  done.push("cancel blocks new jobs and overlapping sync until in-flight work stops");
  const edited = isolated([new TFile("edit.md", "before")]); const file = edited.store.get("edit.md"); let revision;
  edited.instance.upload = async (f, hash, content) => { revision = hash; edited.instance.remember(f.path, hash, hash, content); await edited.instance.app.vault.modifyBinary(f, bytes("after")); };
  await edited.instance.sync(false); assert.equal(edited.instance.pendingChanges, true); assert.equal(edited.instance.settings.state[file.path].hash, digest("before"));
  edited.instance.authorizedRequest = async () => ({ files: [{ path: file.path, revision, size: 6 }] });
  edited.instance.upload = async (f, hash, content) => { assert.equal(Buffer.from(content).toString(), "after"); edited.instance.remember(f.path, hash, hash, content); };
  await edited.instance.sync(false); assert.equal(edited.instance.settings.state[file.path].hash, digest("after"));
  done.push("edits made during upload preserved and sent on next sync");
  const retry = isolated(); retry.instance.settings.serviceStatus = { maxChunkSize: 4194304, fastUploadBytes: 262144 };
  const payload = Buffer.alloc(1200000, 65), attempts = []; let cancelledSessions = 0;
  retry.instance.authorizedRequest = async (route, options) => {
    if (options?.method === "DELETE") { cancelledSessions++; return {}; }
    assert.equal(JSON.parse(options.body).preferredChunkSize, 4194304);
    return { uploadId: "retry-test", chunkSize: 4194304 };
  };
  retry.instance.authorizedBinaryRequest = async (route, method, data) => {
    const index = new URL("https://test.invalid" + route).searchParams.get("index"); attempts.push({ index, hash: digest(data) });
    if (attempts.length === 1) throw new ServiceError("temporary", 503, 1);
    return { json: attempts.length === 3 ? { complete: true, record: { revision: digest(payload) } } : { complete: false } };
  };
  await retry.instance.upload(new TFile("retry.txt", payload), digest(payload), bytes(payload), null);
  assert.equal(attempts.length, 3); assert.deepEqual(attempts[0], attempts[1]); assert.equal(cancelledSessions, 0);
  done.push("chunk retry sends identical bytes/index; completed upload not cancelled");
  console.log("PASS: " + done.join("; "));
})().catch(error => { console.error(error); process.exitCode = 1; });
